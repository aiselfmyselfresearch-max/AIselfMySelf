def _lit(
    material_id: str,
    group: int,
    title: str,
    authors: list[str],
    year: int,
    url: str,
    version_note: str,
    passage: str,
    context: str,
    source_note: str,
    invitation: str,
    scope: str,
    status: str,
    note: str,
    motif_ids: tuple[str, ...],
) -> dict[str, Any]:
    return {
        "material_id": material_id,
        "kind": "literary_text",
        "title": title,
        "source": {
            "source_id": f"SRC-{material_id}",
            "title": title,
            "authors": authors,
            "year": year,
            "url": url,
            "version_note": version_note,
        },
        "passage": passage,
        "passage_language": "ja",
        "context": context,
        "source_note": source_note,
        "literary_invitation": invitation,
        "scope_note": scope,
        "motif_ids": list(motif_ids),
        "verification": {
            "status": status,
            "checked_at": "2026-10-24",
            "method": "既知の書誌・版・該当箇所を内部知識で再確認。外部照合はしていない。"
            if status != "verified"
            else "本セッション中に外部検索で標題・識別子を照合。",
            "note": note,
        },
        "origin": {
            "repository": REPO,
            "commit": COMMIT,
            "source_record_id": f"SRC-{material_id}",
            "evidence_record_id": f"LIT-{material_id}",
            "source_record_path": REPORT,
            "evidence_record_path": REPORT,
        },
        "group": group,
    }


def _ev(
    material_id: str,
    group: int,
    title: str,
    authors: list[str],
    year: int,
    url: str,
    version_note: str,
    passage: str,
    context: str,
    source_note: str,
    invitation: str,
    scope: str,
    status: str,
    note: str,
    motif_ids: tuple[str, ...],
) -> dict[str, Any]:
    record = _lit(
        material_id, group, title, authors, year, url, version_note, passage, context,
        source_note, invitation, scope, status, note, motif_ids,
    )
    record["kind"] = "research_excerpt"
    return record


